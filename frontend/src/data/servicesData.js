// Compatibility export
export const servicesEcosystem = Object.keys(vendorTaxonomy).flatMap(vendorType => {
  const item = vendorTaxonomy[vendorType];
  return Object.keys(item.categories).map(catName => {
    // Guess old baseType
    let baseType = "Service Provider Vendor";
    if (vendorType === "Services") {
      if (catName === "Healthcare Services") baseType = "Hospital Vendor";
      else if (catName === "Education Services") baseType = "Education Vendor";
    } else if (vendorType === "Products") {
      if (catName === "Electronics") baseType = "Electronics Vendor";
      else if (catName === "Home Appliances") baseType = "Electronics Vendor";
      else if (catName === "Furniture") baseType = "Home & Furniture Vendor";
      else baseType = "Store Vendor";
    } else if (vendorType === "Daily Needs") {
      if (catName === "Pharmacy & Healthcare") baseType = "Pharmacy Vendor";
      else if (catName === "Pet Care") baseType = "Store Vendor";
      else baseType = "Grocery Vendor";
    } else if (vendorType === "Food") {
      baseType = "Restaurant Vendor";
    } else if (vendorType === "Stay") {
      baseType = "Hotel Vendor";
    } else if (vendorType === "Jobs") {
      baseType = "Job Vendor";
    }

    return {
      category: catName,
      emoji: item.emoji,
      baseType,
      types: item.categories[catName]
    };
  });
});

export const getBaseVendorType = (vendorType, category, subcategory) => {
  if (!vendorType) return "Store Vendor";
  
  const type = vendorType.split(':')[0].trim();
  const cat = category || "";
  const subcat = subcategory || "";
  
  // 1. Healthcare / Pharmacies handling
  if (subcat === "Pharmacies" || subcat === "Pharmacy" || cat === "Pharmacy & Healthcare") {
    return "Pharmacy Vendor";
  }
  if (cat === "Healthcare Services" || subcat === "Hospitals" || subcat === "Clinics" || subcat === "Dental Care" || subcat === "Eye Care" || subcat === "Telemedicine") {
    if (subcat === "Pharmacies") return "Pharmacy Vendor";
    if (["Hospitals", "Clinics", "Dental Care", "Eye Care", "Telemedicine"].includes(subcat)) {
      return "Hospital Vendor";
    }
    // Other healthcare services that are booking-based (e.g. Physiotherapy, Home Nursing, Ambulance) are Service Providers
    if (["Ambulance Services", "Home Nursing", "Physiotherapy", "Health Checkups", "Medical Equipment", "Diagnostic Centers"].includes(subcat)) {
      return "Service Provider Vendor";
    }
    return "Hospital Vendor"; // default fallback for Healthcare Services
  }

  // 2. Education
  if (cat === "Education Services" || type === "Education") {
    return "Education Vendor";
  }

  // 3. Jobs
  if (type === "Jobs" || cat === "Jobs") {
    return "Job Vendor";
  }

  // 4. Food / Restaurant
  if (type === "Food" || cat === "Food") {
    return "Restaurant Vendor";
  }

  // 5. Stay / Hotel
  if (type === "Stay" || cat === "Stay") {
    return "Hotel Vendor";
  }

  // 6. Travel
  if (type === "Travel") {
    return "Travel Agency Vendor";
  }

  // 7. Services fallback
  if (type === "Services") {
    return "Service Provider Vendor";
  }

  // 7. Products
  if (type === "Products" || type === "Daily Needs") {
    if (cat === "Electronics" || cat === "IT & Office Equipment" || cat === "Home Appliances" || subcat.includes("Electronics")) {
      return "Electronics Vendor";
    }
    if (cat === "Furniture" || subcat.includes("Furniture")) {
      return "Home & Furniture Vendor";
    }
    if (type === "Daily Needs") {
      return "Grocery Vendor";
    }
    return "Store Vendor";
  }

  if (type === "Membership") {
    return "Store Vendor";
  }
  
  return vendorType;
};
